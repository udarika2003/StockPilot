CREATE TABLE categories (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(120) NOT NULL,

                            CONSTRAINT ck_category_name
                                CHECK (name = TRIM(name) AND name <> '')
);

CREATE UNIQUE INDEX uq_categories_name
    ON categories (LOWER(name));

CREATE TABLE products (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          sku VARCHAR(40) NOT NULL UNIQUE,
                          name VARCHAR(120) NOT NULL,
                          category_id BIGINT NOT NULL,
                          unit VARCHAR(10) NOT NULL,
                          selling_price NUMERIC(12, 2) NOT NULL,
                          reorder_level NUMERIC(12, 3) NOT NULL DEFAULT 0,

                          CONSTRAINT fk_products_category
                              FOREIGN KEY (category_id) REFERENCES categories(id),

                          CONSTRAINT ck_product_sku
                              CHECK (sku = UPPER(TRIM(sku)) AND sku <> ''),

                          CONSTRAINT ck_product_name
                              CHECK (name = TRIM(name) AND name <> ''),

                          CONSTRAINT ck_product_unit
                              CHECK (unit IN ('PIECE', 'PACK', 'KG', 'LITRE')),

                          CONSTRAINT ck_product_price
                              CHECK (selling_price > 0),

                          CONSTRAINT ck_product_reorder
                              CHECK (reorder_level >= 0),

                          CONSTRAINT ck_product_reorder_whole
                              CHECK (
                                  unit IN ('KG', 'LITRE')
                                      OR reorder_level = TRUNC(reorder_level)
                                  )
);